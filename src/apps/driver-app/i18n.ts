export type Key = keyof typeof S
/** A parameter may itself be bilingual (a reason code inside a sentence). */
export type Params = Record<string, string | number | Text>

const value = (v: string | number | Text | undefined, lang: Lang) =>
  v == null ? undefined : typeof v === 'object' ? v[lang] : String(v)

const fill = (lang: Lang, s: string, p?: Params) =>
  p ? s.replace(/\{(\w+)\}/g, (_, k: string) => value(p[k], lang) ?? `{${k}}`) : s

export const tr = (lang: Lang, key: Key, p?: Params) => fill(lang, S[key][lang === 'en' ? 0 : 1], p)

/** Both languages at once, for records written now and read later in either language. */
export const both = (key: Key, p?: Params): Text => ({ en: tr('en', key, p), ru: tr('ru', key, p) })
